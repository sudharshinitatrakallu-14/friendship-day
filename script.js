let friendAudio = null;

function stopFriendMusic() {
  if (friendAudio) {
    friendAudio.pause();
    friendAudio.currentTime = 0;
    friendAudio = null;
  }
  const btn = document.getElementById("musicBtn");
  if (btn) btn.textContent = "♫";
}

function playFriendMusic(friend) {
  stopFriendMusic();
  if (!friend || !friend.music) return;

  friendAudio = new Audio(friend.music);
  friendAudio.loop = true;
  friendAudio.volume = 0.55;

  // Start partway through the track, not at 0:00.
  const startPoints = {
    "assets/soodhi.mp3": 42,
    "assets/veeee.mp3": 35,
    "assets/siri.mp3": 28,
    "assets/junnu.mp3": 38,
    "assets/lala.mp3": 32
  };

  const startAt = startPoints[friend.music] || 30;

  friendAudio.addEventListener("loadedmetadata", () => {
    if (friendAudio && Number.isFinite(friendAudio.duration) && friendAudio.duration > startAt) {
      friendAudio.currentTime = startAt;
    }
  }, { once: true });

  friendAudio.play().then(() => {
    const btn = document.getElementById("musicBtn");
    if (btn) btn.textContent = "❚❚";
  }).catch(() => {
    const btn = document.getElementById("musicBtn");
    if (btn) btn.textContent = "♫";
  });
}

document.getElementById("musicBtn")?.addEventListener("click", () => {
  if (!friendAudio) return;
  const btn = document.getElementById("musicBtn");
  if (friendAudio.paused) {
    friendAudio.play();
    if (btn) btn.textContent = "❚❚";
  } else {
    friendAudio.pause();
    if (btn) btn.textContent = "♫";
  }
});

