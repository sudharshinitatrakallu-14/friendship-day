const $ = (id) => document.getElementById(id);

function show(section) {
  ["landing", "login", "reveal", "friendPage"].forEach(id => $(id).classList.add("hidden"));
  $(section).classList.remove("hidden");
  window.scrollTo({top: 0, behavior: "smooth"});
}

function unlock() {
  const code = $("codeInput").value.trim().toLowerCase();
  const friend = friends[code];

  if (!friend) {
    $("error").textContent = "Hmm... nice try 👀 That code isn't yours.";
    return;
  }

  $("error").textContent = "";
  $("revealName").textContent = friend.name;
  window.currentFriend = friend;
  show("reveal");
}

function openFriendPage() {
  const f = window.currentFriend;
  $("friendTitle").textContent = `Hey, ${f.name} 💙`;
  $("friendIntro").textContent = f.intro;
  $("message").textContent = f.message;
  $("memory").textContent = f.memory;
  $("finalMessage").textContent = f.final;

  const photoBox = $("photoBox");
  if (f.photo) {
    photoBox.style.backgroundImage = `url("${f.photo}")`;
    photoBox.classList.remove("hidden");
  } else {
    photoBox.style.backgroundImage = "";
    photoBox.classList.add("hidden");
  }

  $("finalMessage").classList.add("hidden");
  $("finalBtn").classList.remove("hidden");
  show("friendPage");
}

function confetti() {
  const holder = $("confetti");
  for (let i = 0; i < 70; i++) {
    const p = document.createElement("div");
    p.className = "confetti-piece";
    p.style.left = Math.random() * 100 + "vw";
    p.style.setProperty("--x", (Math.random() * 240 - 120) + "px");
    p.style.animationDelay = Math.random() * .5 + "s";
    p.style.background = `hsl(${Math.random() * 360}, 85%, 75%)`;
    holder.appendChild(p);
    setTimeout(() => p.remove(), 2800);
  }
}

